int do_list_tests()
{
    cout << "Valid testbench identifiers:" << endl;
    if (tb_map.empty())
        cout << "\t # No test available #" << endl;
    for (const auto &test_pair : tb_map) {
        cout << "\t" << test_pair.first << endl;
    }
    return 0;
}

int do_test(const string &testname)
{
    // Try to find the test specified by testname from the tb_mab
    auto it = tb_map.find(testname);
    if (it == tb_map.end()) {
        // Not found
        cerr << "Test not found: " << testname << endl;
        return 1;
    }

    // Call the testbench function associated with testname
    specsGlobalConfig.run_start = steady_clock::now(); // wall time of --stats (F-15)
    auto start = high_resolution_clock::now();
    it->second();
    auto stop = high_resolution_clock::now();
    auto duration = duration_cast<microseconds>(stop - start);
    std::cout << "Total runtime: " << duration.count()/1000.0 << " ms" << std::endl;
    // F-15 --stats: the counters of the testbench's ports, next to its trace file
    specsGlobalConfig.writeRunStats();
    return 0;
}

// --param name (F-12): a letter or '_', then letters, digits or '_' (as a .param name)
bool is_param_name(const string &name)
{
    auto is_alpha_plus = [](char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_'; };
    if (name.empty() || !is_alpha_plus(name[0]))
        return false;
    for (char c : name)
        if (!is_alpha_plus(c) && !(c >= '0' && c <= '9'))
            return false;
    return true;
}

// Value of a --param override (F-12): the line ".param name=value" parsed with the netlist grammar
// into a scratch tree, before the netlist (its parameters are not visible). Its random draws (F-02)
// are recorded in pt, as the draws of the root netlist (same stream names)
Variable parse_param_value(const string &name, const string &value, ParseTree &pt)
{
    ParseTree scratch;
    ParserState parser_state;
    parser_state.current_filename = "--param " + name;
    yyscan_t scanner;
    yylex_init_extra(&parser_state, &scanner);
    string line = ".param " + name + "=" + value + "\n";
    YY_BUFFER_STATE buf = yy_scan_string(line.c_str(), scanner);
    yy_switch_to_buffer(buf, scanner);
    yyset_lineno(1, scanner);
    int parsing_result = yyparse(scanner, &scratch);
    yylex_destroy(scanner);

    // exactly one assignment (e.g. not "x=1 y=2")
    if (parsing_result != 0 || scratch.local_assignments.size() != 1 || scratch.local_assignments.count(name) == 0)
    {
        cerr << "Invalid --param value: '" << name << "=" << value << "' (expected name=value)" << endl;
        exit(1);
    }
    for (const auto &d : scratch.draws)
        pt.draws.push_back(d);
    if (scratch.has_drawn && !pt.has_drawn)
    {
        pt.has_drawn = true;
        pt.drawn_seed = scratch.drawn_seed;
        pt.first_draw_where = scratch.first_draw_where;
    }
    return scratch.local_assignments.at(name);
}

int build_circuit(ParseTree &pt, const vector<string> &filenames, string footer="")
{
    yyscan_t scanner;
    ParserState *parser_state = new ParserState();
    // run manifest (F-01): every netlist file opened by the scanners goes to pt's list
    parser_state->input_files = &pt.input_files;
    yylex_init_extra(parser_state, &scanner);

    for(const auto &fname: filenames)
        yy_add_content_from_file(fname, scanner);

    // add footer
    yy_add_content_from_string(footer, "footer autogenerated from command line arguments", scanner);

    // Set up first file
    int res = yy_load_next_buf(scanner);
    if(res != 0)
    {
        cerr << "Expected yy_load_next_buf to return 0" << endl;
        exit(1);
    }

    cout << "╔═══════════════════╗" << endl;
    cout << "║  PARSING CIRCUIT  ║" << endl;
    cout << "╚═══════════════════╝" << endl;

    int parsing_result = yyparse(scanner, &pt);

    //yy_delete_buffer(buf, scanner);
    yylex_destroy(scanner);
    delete parser_state;

    // Return if unsuccessful
    if (parsing_result != 0) {
        return parsing_result;
    }

    for (const auto &p : pt.param_overrides)
    {
        if (!p.second)
            cerr << "Warning: --param " << p.first << ": the netlist has no .param " << p.first << endl;
    }
    // F-02: the random functions must draw with the final seed
    if (!pt.draw_seed_conflict.empty())
    {
        cerr << "Error: " << pt.draw_seed_conflict << "; put .options seed before the first random "
             << "function, or give the seed with --seed" << endl;
        exit(1);
    }

    pt.print();

    cout << "╔══════════════════════╗" << endl;
    cout << "║   BUILDING CIRCUIT   ║" << endl;
    cout << "╚══════════════════════╝" << endl;

    pt.build_circuit();

    return 0;
}

int sc_main(int argc, char *argv[])
{
    // Define command line interface using args
    args::ArgumentParser parser("The Scalable Photonic Event-driven Circuit Simulator.", "");
    args::ValueFlagList<string> file(
        parser, "circuit", "Simulate from circuit file", { 'f', "file" });
    args::ValueFlag<string> set_timescale(parser,
                          "set_timescale",
                          "Set the engine timescale (as log10(timestep/1s))"
                          "(0: seconds, -3: ms, -6:µs, ..., -15: fs)",
                          { 'R', "resolution" });
    args::ValueFlag<string> set_simulator_mode(parser,
                          "set_simulator_mode",
                          "Set simulator mode. Possible values:\n"
                          " - time-domain, event-driven, td (default)\n"
                          " - sampled-time\n"
                          " - frequency-domain, fd",
                          { 'm', "mode"});
    args::Flag run_manual_test(parser,
                          "run_manual_test",
                          "Run manual test function",
                          { 'T', "run-manual-test" });
#if YYDEBUG
    args::Flag debug_netlist_parser(parser,
                          "debug_netlist_parser",
                          "Run with netlist parser debug information",
                          { "debug-parser" });
#endif
    args::ValueFlag<string> set_tracefile(parser,
                          "set_tracefile",
                          "Set the default trace file",
                          { 'o', "output" });
    args::ValueFlagList<string> set_formats(parser,
                          "format",
                          "Output format of the traces: vcd (default), csv or npz (tables of the probed "
                          "signals: time, signal, wavelength, power, complex field), written as "
                          "<output>.vcd/.csv/.npz; repeat it to write several; netlists only",
                          { "format" });
    args::Flag set_no_trace(parser,
                          "no_trace",
                          "Write no trace file and no run manifest (the probes and .save targets are not "
                          "traced); netlists only",
                          { "no-trace" });
    args::ValueFlag<string> export_json(parser,
                          "export_json",
                          "Export json of completed circuit to file",
                          { "json" });
    args::Flag print_version(parser,
                          "version",
                          "Output version information and exit",
                          { "version" });
    args::Flag print_manifest(parser,
                          "print_manifest",
                          "Print the run manifest (version, seed, command line, netlist file hashes) "
                          "to stdout. It is also written next to the default trace file, as "
                          "<trace>.manifest.json",
                          { "print-manifest" });
    args::Flag set_dry_run(parser,
                          "dry_run",
                          "Do not run simulation directives",
                          { 'n', "dryrun" });
    // args::ValueFlag<double> set_reltol(parser,
    //                       "set_reltol",
    //                       "Set the value of the reltol parameter",
    //                       { "reltol" });
    args::ValueFlag<string> set_reltol(parser,
                          "set_reltol",
                          "Set the value of the relative tolerance parameter for field",
                          { "reltol" });
    args::ValueFlag<string> set_abstol(parser,
                          "set_abstol",
                          "Set the value of the absolute tolerance parameter for field",
                          { "abstol" });
    args::ValueFlag<string> set_seed(parser,
                          "set_seed",
                          "Set the master seed of the random streams (decimal integer, 0 to 2^64-1, "
                          "default 0); overrides .options seed",
                          { "seed" });
    args::ValueFlagList<string> set_params(parser,
                          "name=value",
                          "Set the netlist parameter <name>, parsed as in .param name=value; "
                          "overrides the netlist's .param/.assign of the same name (repeatable)",
                          { "param" });

    args::ValueFlag<string> set_maxiter(parser,
                          "set_maxiter",
                          "Set the maximum number of iterations (delta cycles) of the .op/.dc fixed point, "
                          "per operating point or sweep point (decimal integer, default 1000000, 0: no "
                          "limit); overrides .options maxiter",
                          { "maxiter" });
    args::ImplicitValueFlag<string> set_stats(parser,
                          "sections",
                          "Write run statistics: counters of the optical output ports (values scheduled, "
                          "coalesced, processed, emitted, suppressed by abstol/reltol/snap, pending entries, "
                          "last emission) and the wall time, as JSON in <output>.stats.json. Sections: "
                          "summary (default), ports (one row per output port), devices (per device type), "
                          "comma-separated (--stats=ports,devices)",
                          { "stats" }, string("summary"), string());
    args::ValueFlag<string> set_stats_file(parser,
                          "file",
                          "Write the run statistics to this file instead (implies --stats); without it, "
                          "--no-trace or -o \"\" print them to stdout",
                          { "stats-file" });
    args::Flag print_stats(parser,
                          "print_stats",
                          "Also print the run statistics (JSON) to stdout (implies --stats)",
                          { "print-stats" });
    args::ImplicitValueFlag<string> set_progress(parser,
                          "seconds",
                          "Print a progress line (wall time, simulated time, delta cycles) on stderr every "
                          "<seconds> of wall-clock time (default 1); it never changes the simulation; "
                          "netlists only",
                          { "progress" }, string("1"), string());
    args::ValueFlag<string> set_max_events(parser,
                          "set_max_events",
                          "Expert option: stop the run once the optical output ports have processed this "
                          "many pending entries (decimal integer, default 0: no cap); a .tran ends there "
                          "with a warning, an .op/.dc stops with an error; overrides .options maxevents",
                          { "max-events" });

    args::ValueFlag<size_t> set_nrings_crow(parser,
                          "set_nrings_crow",
                          "temporary",
                          { "nrings_crow" });

    args::Flag set_verbose_component_initialization(parser,
                          "set_verbose_component_initialization",
                          "Print components detail before starting simulation",
                          { "vci", "verbose_ci" });

    args::Flag list_tests(parser,
                          "list_tests",
                          "List available testbenches",
                          { 'p', "list-testbenches" });
    args::ValueFlag<string> test(
        parser,
        "test_name",
        "Run the specified testbench (use -p to list available testbenches)",
        { 't', "testbench" });
    args::HelpFlag help(parser, "help", "Display this help menu", { 'h', "help" });
    args::CompletionFlag completion(parser, { "complete" });
    try {
        parser.ParseCLI(argc, argv);
    } catch (const args::Completion &e) {
        cout << e.what();
        return 0;
    } catch (const args::Help &) {
        cout << parser;
        return 0;
    } catch (const args::ParseError &e) {
        cerr << e.what() << endl;
        cerr << parser;
        return 1;
    } catch (const args::ValidationError &e) {
        cerr << e.what() << endl;
        cerr << parser;
        return 1;
    }


    map<string,string> option_overrides;

    // run manifest (F-01)
    specsGlobalConfig.command_line.assign(argv, argv + argc);
    specsGlobalConfig.print_run_manifest = print_manifest.Get();

    if (print_version) {
        std::cout << spx::version::full << std::endl;
        return 0;
    }
    if (set_simulator_mode) {
        const string &s = set_simulator_mode.Get();
        if (strutils::iequals(s, "event-driven") || strutils::iequals(s, "time-domain") || strutils::iequals(s, "td"))
        {
            cout << "Optical ports working in event-driven mode by default" << endl;
            specsGlobalConfig.simulation_mode = OpticalOutputPortMode::EVENT_DRIVEN;
        }
        else if (strutils::iequals(s, "sampled-time"))
        {
            // B-002: OpticalOutputPort::delayedWriteSampledTime() is a TODO that drops every write
            cerr << "Error: sampled-time mode is not implemented" << endl;
            return 1;
        }
        else if (strutils::iequals(s, "frequency-domain") || strutils::iequals(s, "fd"))
        {
            cout << "Simulation mode set to frequency domain" << endl;
            specsGlobalConfig.simulation_mode = OpticalOutputPortMode::FREQUENCY_DOMAIN;
        }
        else
        {
            cerr << "Unknown mode: '" << s << "'" << endl;
            return 1;
        }
        // B-004: an explicit -m takes priority over the default mode of the netlist's analysis
        specsGlobalConfig.simulation_mode_explicit = true;
    }

    if (set_reltol) {
        double reltol_val;
        stringstream ss;
        ss << set_reltol.Get();
        ss >> reltol_val;
        //cout << ss.good() << " " << ss.eof() << " " << ss.fail() << " " << ss.bad() << endl;
        // 0 is allowed (B-153, decision 2026-10-21), negative values are not
        if (!ss.eof() || ss.fail() || !(reltol_val >= 0)) {
            cerr << "Invalid reltol value" << endl;
            return 1;
        }
        option_overrides["reltol"] = set_reltol.Get();
    }
    if (set_abstol) {
        double abstol_val;
        stringstream ss;
        ss << set_abstol.Get();
        ss >> abstol_val;
        if (!ss.eof() || ss.fail() || !(abstol_val >= 0)) {
            cerr << "Invalid abs_tol value" << endl;
            return 1;
        }
        option_overrides["abstol"] = set_abstol.Get();
    }
    if (set_seed) {
        // F-01: set directly (not as a footer .options line), so that it also applies to the
        // testbenches (-t) and keeps the full 64-bit range (netlist numbers are doubles)
        const string &s = set_seed.Get();
        uint64_t seed_val = 0;
        const auto res = std::from_chars(s.data(), s.data() + s.size(), seed_val, 10);
        if (s.empty() || res.ec != std::errc() || res.ptr != s.data() + s.size()) {
            cerr << "Invalid seed value: '" << s << "' (expected a decimal integer from 0 to 18446744073709551615)" << endl;
            return 1;
        }
        specsGlobalConfig.seed = seed_val;
        // takes priority over the netlist's .options seed
        specsGlobalConfig.seed_explicit = true;
    }
    if (set_maxiter) {
        // F-28: set directly, like --seed (full 64-bit range); takes priority over .options maxiter
        const string &s = set_maxiter.Get();
        uint64_t maxiter_val = 0;
        const auto res = std::from_chars(s.data(), s.data() + s.size(), maxiter_val, 10);
        if (s.empty() || res.ec != std::errc() || res.ptr != s.data() + s.size()) {
            cerr << "Invalid maxiter value: '" << s << "' (expected a decimal integer from 0 to 18446744073709551615)" << endl;
            return 1;
        }
        specsGlobalConfig.max_iterations = maxiter_val;
        specsGlobalConfig.max_iterations_explicit = true;
    }
    if (set_stats || set_stats_file || print_stats) {
        // F-15: --stats-file and --print-stats imply --stats (summary)
        unsigned sections = RunStats::SUMMARY;
        if (set_stats && !RunStats::parse_sections(set_stats.Get(), sections)) {
            cerr << "Invalid --stats value: '" << set_stats.Get()
                 << "' (expected summary, ports or devices, comma-separated)" << endl;
            return 1;
        }
        specsGlobalConfig.stats_sections = sections;
        if (set_stats_file) {
            if (set_stats_file.Get().empty()) {
                cerr << "Invalid --stats-file value: empty file name" << endl;
                return 1;
            }
            specsGlobalConfig.stats_filename = set_stats_file.Get();
        }
        specsGlobalConfig.print_stats = print_stats.Get();
    }
    if (set_progress) {
        double period_s = 0;
        stringstream ss;
        ss << set_progress.Get();
        ss >> period_s;
        if (!ss.eof() || ss.fail() || !(period_s > 0) || !std::isfinite(period_s)) {
            cerr << "Invalid --progress value: '" << set_progress.Get() << "' (expected a period in seconds > 0)" << endl;
            return 1;
        }
        specsGlobalConfig.progress_period_s = period_s;
    }
    if (set_max_events) {
        // F-15 expert option, set directly like --maxiter; takes priority over .options maxevents
        const string &s = set_max_events.Get();
        uint64_t max_events_val = 0;
        const auto res = std::from_chars(s.data(), s.data() + s.size(), max_events_val, 10);
        if (s.empty() || res.ec != std::errc() || res.ptr != s.data() + s.size()) {
            cerr << "Invalid max-events value: '" << s << "' (expected a decimal integer from 0 to 18446744073709551615)" << endl;
            return 1;
        }
        specsGlobalConfig.max_events = max_events_val;
        specsGlobalConfig.max_events_explicit = true;
    }
    // F-12: validated here, applied to the netlist parse tree (ignored with -t, like --reltol)
    vector<pair<string, string>> param_overrides;
    for (const auto &s : set_params.Get()) {
        const size_t i_eq = s.find('=');
        const string name = s.substr(0, i_eq);
        const string value = i_eq == string::npos ? "" : s.substr(i_eq + 1);
        if (i_eq == string::npos || !is_param_name(name) || value.empty()
            || value.find_first_of("\r\n") != string::npos) {
            cerr << "Invalid --param value: '" << s << "' (expected name=value)" << endl;
            return 1;
        }
        param_overrides.emplace_back(name, value);
    }
    if (set_verbose_component_initialization) {
        specsGlobalConfig.verbose_component_initialization = set_verbose_component_initialization.Get();
    }
    if (set_nrings_crow) {
        #if BUILD_TB == 1
        if (set_nrings_crow.Get() < 1 || set_nrings_crow.Get() > 1024)
        {
            cerr << "Invalid --nrings_crow value (expected 1..1024)" << endl;
            return 1;
        }
        nrings_crow = set_nrings_crow.Get();
        #endif
    }
    if (set_timescale) {
        int timescale_val;
        stringstream ss;
        ss << set_timescale.Get();
        ss >> timescale_val;
        if (!ss.eof() || ss.fail() || timescale_val > 0 || timescale_val < -15) {
            cerr << "Invalid resolution value" << endl;
            return 1;
        }
        option_overrides["timescale"] = set_timescale.Get();
    }
    if (run_manual_test) {
        return 0;
    }
#if YYDEBUG
    if (debug_netlist_parser) {
        yydebug = 1;
    }
#endif
    if (list_tests) {
        return do_list_tests();
    }
    if (set_formats) {
        // F-05: exactly the listed formats (the VCD only if listed)
        if (set_no_trace) {
            cerr << "Error: --no-trace and --format cannot be combined" << endl;
            return 1;
        }
        specsGlobalConfig.trace_vcd = false;
        for (const auto &f : set_formats.Get()) {
            if (strutils::iequals(f, "vcd"))
                specsGlobalConfig.trace_vcd = true;
            else if (strutils::iequals(f, "csv"))
                specsGlobalConfig.trace_csv = true;
            else if (strutils::iequals(f, "npz"))
                specsGlobalConfig.trace_npz = true;
            else {
                cerr << "Invalid --format value: '" << f << "' (expected vcd, csv or npz)" << endl;
                return 1;
            }
        }
    }
    if (set_no_trace) {
        // F-05: as -o "" (no trace file, no run manifest file); wins over -o
        cout << "Tracing disabled (--no-trace)" << endl;
        specsGlobalConfig.trace_filename = "";
    }
    else if (set_tracefile) {
        cout << "Using trace file: " << set_tracefile.Get() << endl;
        // TODO: validate filename
        specsGlobalConfig.trace_filename = set_tracefile.Get();
    }

    if (file) {
        stringstream footer;
        for (const auto &option_override: option_overrides)
        {
            footer << ".options " << option_override.first << "=" << option_override.second << endl;
        }
        footer << endl;
        //cout << footer.str() << endl;
        ParseTree pt;
        // the last one wins if a name is given twice
        for (const auto &p : param_overrides)
            pt.set_param_override(p.first, parse_param_value(p.first, p.second, pt));
        int parse_result = build_circuit(pt, file.Get(), footer.str());
        if (parse_result)
        {
            cerr << "Parsing failed with code " << parse_result << endl;
            exit(parse_result);
        }
        // after build_circuit(): the .include files of subcircuit bodies are opened while flattening (B-150)
        specsGlobalConfig.netlist_files = pt.input_files;
        if (set_dry_run.Get() && specsGlobalConfig.print_run_manifest)
        {
            // no prepareSimulation() in a dry run, and no trace file is written
            cout << RunManifest(specsGlobalConfig, "").to_json() << flush;
            specsGlobalConfig.print_run_manifest = false;
        }
        string json_filename = export_json.Get();
        if (!json_filename.empty())
        {
            ofstream outfile;
            outfile.open(json_filename, ios::out | ios::trunc);
            if (!outfile)
            {
                cerr << "Error: cannot open JSON output file \"" << json_filename << "\"" << endl;
                return 1;
            }
            outfile << pt.to_json();
            outfile.close();
            cout << "Exported flattened circuit as JSON > " << json_filename << endl;
        }

        if (!set_dry_run.Get())
        {
            cout << "╔══════════════════════╗" << endl;
            cout << "║      SIMULATION      ║" << endl;
            cout << "╚══════════════════════╝" << endl;

            specsGlobalConfig.runAnalysis();
        }
        else
        {
            cout << "╔══════════════════════╗" << endl;
            cout << "║  SIMULATION SKIPPED  ║" << endl;
            cout << "╚══════════════════════╝" << endl;
        }

        cout << "╔═══════════════════╗" << endl;
        cout << "║        DONE       ║" << endl;
        cout << "╚═══════════════════╝" << endl;
        return 0;
    }
    if (test) {
        return do_test(test.Get());
    }

    // Print help if nothing else was done
    cout << parser;
    return 1;
}
